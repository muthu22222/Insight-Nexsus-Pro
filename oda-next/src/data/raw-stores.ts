export function calculateDistance(
  lat1: number,
  lng1: number,
  lat2: number,
  lng2: number
): number {
  const R = 6371; // Earth's radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLng / 2) *
      Math.sin(dLng / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return parseFloat((R * c).toFixed(1));
}

export function getRawStores(
  userLat?: number,
  userLng?: number,
  category?: string,
  searchQuery?: string
): RawStore[] {
  const hasUserCoords = typeof userLat === 'number' && typeof userLng === 'number' && userLat !== 0;

  let filtered = RAW_STORES.map((store) => {
    const distance = hasUserCoords
      ? calculateDistance(userLat!, userLng!, store.lat, store.lng)
      : undefined;
    return {
      ...store,
      distance,
    };
  });

  if (category && category !== 'All') {
    const targetCat = category.toLowerCase().trim();
    filtered = filtered.filter(
      (s) => s.category.toLowerCase().trim() === targetCat
    );
  }

  if (searchQuery && searchQuery.trim()) {
    const query = searchQuery.toLowerCase().trim();
    filtered = filtered.filter(
      (s) =>
        s.name.toLowerCase().includes(query) ||
        s.address.toLowerCase().includes(query) ||
        s.city.toLowerCase().includes(query) ||
        s.category.toLowerCase().includes(query)
    );
  }

  // If user coords available, sort by closest first!
  if (hasUserCoords) {
    filtered.sort((a, b) => (a.distance ?? 999999) - (b.distance ?? 999999));
  }

  return filtered;
}
